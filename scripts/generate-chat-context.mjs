// Embeds docs/portfolio-content.md into a TS module so the chatbot (Vercel Edge
// function + local Express server) can use it without filesystem access at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('../docs/portfolio-content.md', import.meta.url));
const out = fileURLToPath(new URL('../api/_lib/portfolio-content.generated.ts', import.meta.url));

const markdown = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/generate-chat-context.mjs from docs/portfolio-content.md.\n` +
    `// Do not edit by hand - edit the markdown file and run \`npm run generate:chat-context\`.\n` +
    `export const PORTFOLIO_CONTENT: string = ${JSON.stringify(markdown)};\n`,
);

console.log(`Wrote ${out} (${markdown.length} chars)`);
